"""Build the cast tunnel rib. Local Blender also exports the indexed mobile mesh."""
import bpy
import math

verts, faces = [], []
# Cross-section of the rib, including two raised edges and a recessed centre.
section = [(-.075, .024), (-.067, .057), (-.047, .057), (-.040, .036),
           (.040, .036), (.047, .057), (.067, .057), (.075, .024),
           (.065, -.012), (-.065, -.012)]
path = [(1, 0, .055), (1, 0, .59)]
for i in range(1, 25):
    angle = math.pi*i/24
    path.append((math.cos(angle), math.sin(angle), .59+.65*math.sin(angle)))
path.append((-1, 0, .055))
for i, (nx, nz, height) in enumerate(path):
    for j, (depth, radial) in enumerate(section):
        verts.append((nx*(.65+radial), depth, height+nz*radial))
        if i:
            b = i*len(section)+j
            c = i*len(section)+(j+1)%len(section)
            faces.append((b-len(section), c-len(section), c, b))
mesh = bpy.data.meshes.new('Arcade19 rib profile')
mesh.from_pydata(verts, [], faces)
mesh.update()
portal = bpy.data.objects.new('ARC19 • flanged tunnel rib', mesh)
bpy.context.collection.objects.link(portal)
metal = bpy.data.materials.new('Arcade19 • bead-blasted titanium')
metal.diffuse_color = (.35,.45,.50,1)
metal.use_nodes = True
shader = metal.node_tree.nodes.get('Principled BSDF')
shader.inputs['Base Color'].default_value = (.35,.45,.50,1)
shader.inputs['Metallic'].default_value = .8
shader.inputs['Roughness'].default_value = .28
mesh.materials.append(metal)

# Extend the lower diffuser with four tapered carbon strakes in chassis space.
vanes, panels = [], []
for offset in (-.049, -.021, .021, .049):
    start = len(vanes)
    for side in (-.0014, .0014):
        for x, height in [(-.115,.013),(-.152,.022),(-.154,.012),(-.125,.008)]:
            vanes.append((x,offset+side,height))
    for quad in [(0,1,2,3),(7,6,5,4),(0,4,5,1),(1,5,6,2),(2,6,7,3),(3,7,4,0)]:
        panels.append(tuple(start+i for i in quad))
diffuser = bpy.data.meshes.new('Arcade19 diffuser')
diffuser.from_pydata(vanes, [], panels)
diffuser.update()
bpy.context.collection.objects.link(bpy.data.objects.new('ARC19 • carbon diffuser',diffuser))

if __name__ == '__main__' and '--export-game' in __import__('sys').argv:
    import json
    from pathlib import Path
    with (Path(__file__).resolve().parents[1]/'src/render/portal-mesh.js').open('w') as target:
        target.write('// Generated by blender/arcade_portal.py with --export-game.\n')
        for name, part in [('portal',mesh),('diffuser',diffuser)]:
            part.calc_loop_triangles()
            arrays = {'Vertices':[round(q,5) for v in part.vertices for q in (v.co.x,v.co.z,-v.co.y)],
                      'Triangles':[q for t in part.loop_triangles for q in t.vertices]}
            for suffix, data in arrays.items():
                target.write('export const '+name+suffix+'='+json.dumps(data,separators=(',',':'))+';\n')
